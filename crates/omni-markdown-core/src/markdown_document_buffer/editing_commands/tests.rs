//! Independent CodeMirror command comparisons and canonical transaction boundary regressions.

use super::*;
use serde::Deserialize;

/// Frozen upstream command outputs plus versions and executable-source digest for reproducibility.
#[derive(Deserialize)]
struct ReferenceCorpus {
    commands_sha256: String,
    state_version: String,
    commands_version: String,
    cases: Vec<ReferenceCase>,
}

/// One primary selection expressed in the original native document's physical UTF-16 coordinates.
#[derive(Deserialize)]
struct ReferenceCase {
    action: String,
    input: String,
    handled: bool,
    anchor: usize,
    head: usize,
    text: String,
    anchor_after: usize,
    head_after: usize,
}

/// Native text, direction and endpoint association match actual baseline commands, including CRLF.
#[test]
fn indentation_matches_original_codemirror_command_corpus() {
    // The oracle is generated by executing upstream commands, never by the Rust algorithm under test.
    let corpus: ReferenceCorpus =
        serde_json::from_str(include_str!("reference_cases.json")).unwrap();
    assert_eq!(
        corpus.commands_sha256,
        "6954654363ad59d89a9264f4c402f6667720665fe3bb6c9966a210947c14c164"
    );
    assert_eq!(corpus.state_version, "6.7.1");
    assert_eq!(corpus.commands_version, "6.11.0");
    assert_eq!(corpus.cases.len(), 2178);
    for case in corpus.cases {
        // Every test fixture has an isolated file and independent live/history state.
        let (_directory, mut document) = fixture(&case.input, 1024 * 1024);
        let command = match case.action.as_str() {
            // Source Tab always invokes the selected-line indentation command.
            "indent-more" => MarkdownEditingCommand::IndentMore,
            // Source Shift-Tab consumes a no-op when none of the selected lines can be outdented.
            "indent-less" => MarkdownEditingCommand::IndentLess,
            // An unknown serialized command is corpus drift rather than an implicit product fallback.
            _ => panic!("unknown reference action"),
        };
        let outcome = document
            .apply_editing_command(
                command,
                MarkdownTextSelection {
                    anchor_utf16: case.anchor,
                    head_utf16: case.head,
                },
            )
            .unwrap();
        assert_eq!(
            !matches!(outcome, MarkdownEditingOutcome::NotHandled),
            case.handled
        );
        assert_eq!(
            text(&document),
            case.text,
            "{} {:?} {} {}",
            case.action,
            case.input,
            case.anchor,
            case.head
        );
        // A handled no-op preserves the caller's native selection without requiring canonical mutation.
        let selection = match outcome {
            // A committed command's receipt is authoritative for native selection restoration.
            MarkdownEditingOutcome::Changed(edit) => edit.selection_after,
            // A consumed no-op retains the original native primary selection exactly.
            MarkdownEditingOutcome::Unchanged => MarkdownTextSelection {
                anchor_utf16: case.anchor,
                head_utf16: case.head,
            },
            // The baseline always handles these indentation bindings; fallback would be a regression.
            MarkdownEditingOutcome::NotHandled => unreachable!("indentation commands are consumed"),
        };
        assert_eq!(
            selection,
            MarkdownTextSelection {
                anchor_utf16: case.anchor_after,
                head_utf16: case.head_after
            },
            "{} {:?} {} {}",
            case.action,
            case.input,
            case.anchor,
            case.head
        );
    }
}

/// Own an isolated synthetic note while exercising the canonical document API.
fn fixture(text: &str, budget: u64) -> (tempfile::TempDir, MarkdownDocumentBuffer) {
    // No source or output touches user notes; the immutable snapshot outlives no fixture owner.
    let directory = tempfile::tempdir().unwrap();
    let path = directory.path().join("keyboard.md");
    std::fs::write(&path, text).unwrap();
    let document = MarkdownDocumentBuffer::open(&path, budget).unwrap();
    (directory, document)
}

/// Collect only disposable assertion output; production commands never materialize the document.
fn text(document: &MarkdownDocumentBuffer) -> String {
    // A test-owned writer makes exact byte comparisons independent of native presentation.
    let mut bytes = Vec::new();
    document.write_to(&mut bytes).unwrap();
    String::from_utf8(bytes).unwrap()
}

/// Two selected lines indent in one undo step while an endpoint at the next line start excludes it.
#[test]
fn indentation_excludes_trailing_line_and_preserves_history_orientation() {
    let (_directory, mut document) = fixture("first\nsecond\nthird", 1024);
    let before = MarkdownTextSelection {
        anchor_utf16: 13,
        head_utf16: 0,
    };
    let changed = document
        .apply_editing_command(MarkdownEditingCommand::IndentMore, before)
        .unwrap();
    assert_eq!(text(&document), "  first\n  second\nthird");
    assert_eq!(
        document.selection(),
        MarkdownTextSelection {
            anchor_utf16: 17,
            head_utf16: 2
        }
    );
    assert!(matches!(changed, MarkdownEditingOutcome::Changed(_)));
    assert_eq!(document.storage_profile().undo_entries, 1);
    assert_eq!(document.undo(), Some(before));
    assert_eq!(text(&document), "first\nsecond\nthird");
    assert!(document.redo().is_some());
    assert_eq!(text(&document), "  first\n  second\nthird");
}

/// Outdent normalizes tabs/Unicode whitespace and consumes a no-op without changing dirty state.
#[test]
fn outdent_columns_and_noop_are_distinct_from_native_fallback() {
    let (_directory, mut document) = fixture(" \tword\n\u{feff}\u{2003}word\nword", 1024);
    let selection = MarkdownTextSelection {
        anchor_utf16: 0,
        head_utf16: document.utf16_len(),
    };
    document
        .apply_editing_command(MarkdownEditingCommand::IndentLess, selection)
        .unwrap();
    assert_eq!(text(&document), "  word\nword\nword");
    let (_empty, mut clean) = fixture("word", 1024);
    let profile = clean.storage_profile();
    let generation = clean.generation();
    assert_eq!(
        clean
            .apply_editing_command(
                MarkdownEditingCommand::IndentLess,
                MarkdownTextSelection::caret(0)
            )
            .unwrap(),
        MarkdownEditingOutcome::Unchanged
    );
    assert_eq!(clean.storage_profile(), profile);
    assert_eq!(clean.generation(), generation);
    assert!(!clean.is_dirty());
}

/// Rejected growth restores all command state, and a sparse giant line keeps its body shared.
#[test]
fn indentation_capacity_rejection_is_atomic_and_sparse_bodies_stay_shared() {
    // Growth beyond the live-document budget fails before acquiring or publishing marker storage.
    let (_directory, mut document) = fixture("x", 2);
    let profile = document.storage_profile();
    assert!(matches!(
        document.apply_editing_command(
            MarkdownEditingCommand::IndentMore,
            MarkdownTextSelection::caret(0)
        ),
        Err(MarkdownDocumentBufferError::DocumentTooLarge)
    ));
    assert_eq!(document.storage_profile(), profile);
    assert_eq!(text(&document), "x");
    // A giant untouched line remains in shared original pieces, requiring only its literal prefix.
    let body = "x".repeat(1024 * 1024);
    let (_large, mut document) = fixture(&body, (body.len() + 2) as u64);
    document
        .apply_editing_command(
            MarkdownEditingCommand::IndentMore,
            MarkdownTextSelection::caret(0),
        )
        .unwrap();
    assert_eq!(document.storage_profile().appended_edit_bytes, 2);
    assert_eq!(document.byte_len(), body.len() + 2);
}

/// Dense commands bound metadata by chunk count and roll back a partially prepared failed command.
#[test]
fn dense_indentation_streams_and_failed_preparation_restores_the_append_tail() {
    // More than 4096 selected lines exercise the fixed-scratch path rather than per-line tree edits.
    let source = "x\n".repeat(8192);
    let (_directory, mut document) = fixture(&source, (source.len() * 8) as u64);
    let selection = MarkdownTextSelection {
        anchor_utf16: 0,
        head_utf16: source.len(),
    };
    document
        .apply_editing_command(MarkdownEditingCommand::IndentMore, selection)
        .unwrap();
    let expected = "  x\n".repeat(8192);
    assert_eq!(text(&document), expected);
    let profile = document.storage_profile();
    assert_eq!(profile.undo_entries, 1);
    assert!(profile.piece_count <= expected.len().div_ceil(ORIGINAL_PIECE_BYTES) * 2 + 2);
    assert_eq!(document.undo(), Some(selection));
    assert_eq!(text(&document), source);
    assert!(document.redo().is_some());
    let outdent_selection = MarkdownTextSelection {
        anchor_utf16: 0,
        head_utf16: document.utf16_len(),
    };
    document
        .apply_editing_command(MarkdownEditingCommand::IndentLess, outdent_selection)
        .unwrap();
    assert_eq!(text(&document), source);

    // Prior edits may exhaust cumulative append storage even when the next live result would fit.
    let (_small, mut exhausted) = fixture("\t\tx", 16);
    for _ in 0..7 {
        // Append and undo retain the session's consumed edit bytes while restoring the tiny live text.
        exhausted
            .insert_utf16(3, "zz", MarkdownTextSelection::caret(5))
            .unwrap();
        assert!(exhausted.undo().is_some());
    }
    let profile = exhausted.storage_profile();
    let generation = exhausted.generation();
    assert!(matches!(
        exhausted.apply_editing_command(
            MarkdownEditingCommand::IndentLess,
            MarkdownTextSelection::caret(2)
        ),
        Err(MarkdownDocumentBufferError::EditBufferLimitExceeded)
    ));
    assert_eq!(exhausted.storage_profile(), profile);
    assert_eq!(exhausted.generation(), generation);
    assert_eq!(text(&exhausted), "\t\tx");
}
